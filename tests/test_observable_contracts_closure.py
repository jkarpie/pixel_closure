# The selector and annotation layer, added 2026-08-13.
#
# ``annotate_manifest`` is what turns "a missing citation or an ambiguous selector"
# into a generation-time error (its own docstring).  Until now nothing had ever
# watched it do that: every call in this file passes a real manifest whose records
# all match exactly one contract, so the ``len(matches) != 1`` raise had no test,
# and the ``commondata_name`` selector -- used by 22 of the 52 dataset records, i.e.
# every EW/NNPDF extension candidate -- had never been evaluated against any record
# at all, because the committed manifests carry no ``"datasets"`` section for it to
# match.  Both are exercised here on a synthetic manifest rather than by waiting for
# a candidate to be promoted.
# ---------------------------------------------------------------------------


def _commondata_selected_contract(contracts):
    """Return the first contract that selects by ``commondata_name``, or fail loudly."""
    for record in contracts["datasets"]:
        if "commondata_name" in record["selector"]:
            return record
    raise AssertionError("no contract selects by commondata_name; fixture assumption broken")


@pytest.mark.parametrize("alias", ["commondata_name", "setname", "source_id"])
def test_the_commondata_name_selector_matches_through_its_whole_fallback_chain(alias):
    """A ``"datasets"`` record matches its contract under all three name spellings.

    Oracle ``F1``: selector routing, no numerics.  ``_selector_matches``
    (``contracts.py:248-251``) reads ``record.get("commondata_name",
    record.get("setname", record.get("source_id")))`` -- a three-deep fallback chain
    that, per the coverage index, no test in the suite had ever entered.  Each
    parametrized case supplies the name under exactly one of the three keys, so a
    dropped link in the chain fails one case and leaves the others green, naming the
    broken link instead of reporting "selectors are broken".

    The negative half is what makes this more than a smoke test: the same record
    under a *wrong* name must match zero contracts, so a ``_selector_matches`` that
    fell through to ``return True`` whenever the key was absent -- the natural
    failure of a fallback chain -- would fail here even though every positive case
    still passed.  The section is checked too: the identical record under
    ``section="exp"`` matches nothing, since ``_selector_matches``'s first line
    compares sections before looking at any name.
    """
    contracts = load_observable_contracts()
    contract = _commondata_selected_contract(contracts)
    name = contract["selector"]["commondata_name"]

    matches = matching_contracts(contracts, "datasets", {alias: name})
    assert [record["id"] for record in matches] == [contract["id"]]
    # Negative: an unknown name matches nothing.  Without this, a selector that
    # ignored the name entirely would pass every positive case above.
    assert matching_contracts(contracts, "datasets", {alias: "not_a_commondata_set"}) == []
    # And the section gate still applies to the very same record.
    assert matching_contracts(contracts, "exp", {alias: name}) == []


def test_annotate_manifest_refuses_a_datasets_record_matching_other_than_one_contract():
    """The ambiguous/zero-match raise fires, and the exactly-one case annotates.

    Oracle ``F1``.  ``annotate_manifest``'s ``len(matches) != 1`` branch
    (``contracts.py:287-291``) is the mechanism its own docstring credits with making
    an ambiguous selector "a generation-time error instead of a reporting-time
    warning", and nothing had ever triggered it.  Both sides of ``!= 1`` are covered:
    zero matches (an unknown ``commondata_name``) and two matches (a second contract
    cloned onto the same selector), each matched on the reported *count* in the
    message rather than on ``ContractError`` alone -- the two arms raise the same
    class from the same line, and a guard that reported "2" when it meant "0" would
    otherwise be invisible.

    The third case is the control, and it doubles as the first end-to-end exercise of
    the ``"datasets"`` section in ``annotate_manifest``'s *default* ``sections`` tuple
    (``contracts.py:274``) -- the landing zone for a promoted EW/NNPDF candidate,
    which today's committed manifests never populate.  It asserts the annotation was
    actually written and carries the matched contract's own id and citations, so the
    guard cannot be satisfied by a function that raises on everything, nor by one
    that walks the section without annotating it.
    """
    contracts = load_observable_contracts()
    contract = _commondata_selected_contract(contracts)
    name = contract["selector"]["commondata_name"]

    with pytest.raises(ContractError, match="matches 0 contracts"):
        annotate_manifest(
            {"datasets": [{"name": "orphan", "commondata_name": "not_a_commondata_set"}]},
            contracts=contracts,
        )

    ambiguous = copy.deepcopy(contracts)
    clone = copy.deepcopy(contract)
    clone["id"] = str(contract["id"]) + ".clone"
    ambiguous["datasets"].append(clone)
    with pytest.raises(ContractError, match="matches 2 contracts"):
        annotate_manifest(
            {"datasets": [{"name": "ambiguous", "commondata_name": name}]},
            contracts=ambiguous,
        )

    # Control + the "datasets" section end to end: exactly one match annotates.
    annotated = annotate_manifest(
        {"datasets": [{"name": "promoted", "commondata_name": name}]},
        contracts=contracts,
    )
    record = annotated["datasets"][0]
    assert record["contract_id"] == contract["id"]
    assert record["classification"] == contract["classification"]
    assert record["citation_keys"] == list(contract["citation_keys"])
    assert record["provenance"]["contract_id"] == contract["id"]


def test_contract_artifact_provenance_digests_the_two_files_it_names(tmp_path):
    """The stamped sha256 digests are of the real contract and bibliography bytes.

    ``contract_artifact_provenance`` is ``__all__``-exported and 0% covered, yet both
    closure suites' ``generate.py`` and ``closure_audit.py`` call it to bake these
    digests into every generated manifest's provenance record -- a provenance stamp
    nobody had ever checked stamps the right bytes.

    Oracle ``A1`` for the digests: ``hashlib.sha256`` over bytes this test reads
    itself, so the expected value comes from the file rather than from the function.
    That alone would still pass if the function hashed the wrong file, so the second
    half is the load-bearing one: pointed at a scratch ``root`` holding *different*
    contract and bibliography bytes, both digests must change, and each must equal
    the digest of the scratch file with the corresponding name.  A function returning
    a constant, or reading the repository copy regardless of ``root``, fails there.
    The bibliography path is taken from ``contracts["bibliography"]["path"]``, which
    is the one thing that decides *which* second file gets stamped.
    """
    contracts = load_observable_contracts()
    contract_path = ROOT / "observable_contracts.yaml"
    bibliography_path = ROOT / contracts["bibliography"]["path"]

    provenance = contract_artifact_provenance(contracts)
    assert provenance["observable_contracts"] == contract_path.name
    assert provenance["bibliography"] == bibliography_path.name
    assert provenance["observable_contracts_sha256"] == hashlib.sha256(
        contract_path.read_bytes()
    ).hexdigest()
    assert provenance["bibliography_sha256"] == hashlib.sha256(
        bibliography_path.read_bytes()
    ).hexdigest()

    # Different bytes under a different root must give different digests -- the half
    # that a constant-returning implementation would fail.
    (tmp_path / "observable_contracts.yaml").write_bytes(b"not the real contracts\n")
    (tmp_path / bibliography_path.name).write_bytes(b"not the real bibliography\n")
    scratch = contract_artifact_provenance(contracts, root=tmp_path)
    assert scratch["observable_contracts_sha256"] != provenance["observable_contracts_sha256"]
    assert scratch["bibliography_sha256"] != provenance["bibliography_sha256"]
    assert scratch["observable_contracts_sha256"] == hashlib.sha256(
        b"not the real contracts\n"
    ).hexdigest()
    assert scratch["bibliography_sha256"] == hashlib.sha256(
        b"not the real bibliography\n"
    ).hexdigest()


def test_lattice_selected_rows_reconcile_with_the_generated_full_manifest():
    """The lattice half of the ``exp``/``dy`` reconciliation, which had no equivalent.

    Oracle ``A3``: the count comes from the committed, generated manifest;
    ``selected_rows`` comes from the yaml.  The sibling completeness test does check
    the lattice totals (``== 234``, ``all(... == 18)``), but against *independently
    hardcoded literals* -- so an edit that moved a lattice contract's
    ``selected_rows`` away from what generation actually emits was caught nowhere in
    this file, which is precisely the drift
    ``test_selected_point_counts_reconcile_with_generated_full_manifest`` exists to
    catch for ``exp``/``dy``.

    The lattice unit differs from ``exp``/``dy``'s and the assertion follows it: one
    lattice contract covers a whole ensemble, so its ``selected_rows`` (18) is the
    number of *manifest records* selected by that contract, not the row count of any
    one data file.  ``matching_contracts`` is what partitions the records, and
    ``len(matches) == 1`` is asserted first, so an ambiguous ``name_regex`` cannot
    quietly inflate one ensemble's tally by stealing another's records.  Both
    committed suites are checked; the sum is asserted too, so a contract that matched
    nothing would fail here rather than being skipped by an empty ``Counter``.
    """
    contracts = load_observable_contracts()
    by_id = contract_index(contracts)
    lattice_ids = sorted(
        dataset_id for dataset_id in by_id if dataset_id.startswith("lattice.")
    )
    assert lattice_ids, "no lattice contracts in the table; fixture assumption broken"

    for suite in ("closure_JAM_truth", "closure_NNPDF_truth"):
        manifest = _manifest(suite)
        seen = Counter()
        for record in manifest["lattice"]:
            matches = matching_contracts(contracts, "lattice", record)
            assert len(matches) == 1
            seen[str(matches[0]["id"])] += 1
        for dataset_id in lattice_ids:
            assert seen[dataset_id] == by_id[dataset_id]["selected_rows"]
        assert sum(seen.values()) == sum(
            by_id[dataset_id]["selected_rows"] for dataset_id in lattice_ids
        )
