# ---------------------------------------------------------------------------
# The guards themselves.
#
# Added 2026-08-13.  Five assertions in this file were found to be unreachable in
# the strict sense: each re-checks an invariant that ``load_observable_contracts()``
# has *already* enforced and raised on, one to five lines earlier.  If the invariant
# were ever violated the loader would raise first, so the test would ERROR during
# setup and the assertion would never execute -- it cannot fail, and it cannot pass
# for a reason either.  Meanwhile the ``raise ContractError`` branches doing the real
# work were reached by no test anywhere.
#
# The fix is the inverse of the usual one: not a better fixture, but a deliberately
# BROKEN one.  Each case below corrupts a deep copy of the committed table in exactly
# one way and asserts the specific error.  Corrupting a copy of the real table rather
# than hand-building a minimal dict matters -- a minimal dict would drift out of shape
# as the schema grows and start failing for the wrong reason, which is how a guard
# test quietly stops testing its guard.
# ---------------------------------------------------------------------------


def _corrupt(mutate):
    """Deep-copy the committed contracts, apply one corruption, return the result."""
    contracts = copy.deepcopy(load_observable_contracts())
    mutate(contracts)
    return contracts


def _duplicate_dataset_id(contracts):
    contracts["datasets"].append(copy.deepcopy(contracts["datasets"][0]))


def _duplicate_citation_key(contracts):
    papers = contracts["bibliography"]["papers"]
    clone = copy.deepcopy(papers[0])
    clone["inspire_id"] = max(int(p["inspire_id"]) for p in papers) + 1
    papers.append(clone)


def _duplicate_inspire_id(contracts):
    papers = contracts["bibliography"]["papers"]
    clone = copy.deepcopy(papers[0])
    clone["citation_key"] = clone["citation_key"] + "_clone"
    papers.append(clone)


def _unresolved_citation_key(contracts):
    for record in contracts["datasets"]:
        if record["citation_keys"]:
            record["citation_keys"] = list(record["citation_keys"]) + ["NoSuchPaper2099"]
            return
    raise AssertionError("no dataset carries a citation key; fixture assumption broken")


def _selects_more_rows_than_exist(contracts):
    record = contracts["datasets"][0]
    record["source_rows"] = 10
    record["selected_rows"] = 11
    record["selectable"] = True


def _selectable_disagrees_with_row_count(contracts):
    for record in contracts["datasets"]:
        if int(record["selected_rows"]) > 0:
            record["selectable"] = False
            return
    raise AssertionError("no dataset selects any row; fixture assumption broken")


def _mode_references_unknown_dataset(contracts):
    mode = next(iter(contracts["full_closure_modes"].values()))
    mode["dataset_ids"] = list(mode["dataset_ids"]) + ["definitely_not_a_dataset"]


def _mode_repeats_a_dataset(contracts):
    mode = next(iter(contracts["full_closure_modes"].values()))
    ids = list(mode["dataset_ids"])
    mode["dataset_ids"] = ids + [ids[0]]


def _reuses_a_doi_across_two_papers(contracts):
    papers = contracts["bibliography"]["papers"]
    with_doi = [paper for paper in papers if paper.get("doi")]
    if len(with_doi) < 2:
        raise AssertionError("fewer than two papers carry a doi; fixture assumption broken")
    # Assign, do not clone: a cloned paper would trip the duplicate-citation-key
    # guard (which runs first) and this case would silently test that instead.
    with_doi[1]["doi"] = with_doi[0]["doi"]


def _inspire_ids_disagree_with_citation_keys(contracts):
    for record in contracts["datasets"]:
        if record["citation_keys"] and record.get("inspire_ids"):
            record["inspire_ids"] = []
            return
    raise AssertionError("no dataset carries both fields; fixture assumption broken")


def _physics_record_keeps_an_unresolved_marker(contracts):
    for record in contracts["datasets"]:
        if record["classification"] == "physics":
            record["operator"]["nuclear"] = "unknown"
            return
    raise AssertionError("no physics dataset in the table; fixture assumption broken")


def _mode_selects_a_gated_dataset(contracts):
    gated = next(
        record for record in contracts["datasets"] if not record["selectable"]
    )
    mode = next(iter(contracts["full_closure_modes"].values()))
    # Adding a genuinely gated id, rather than flipping a selected record's
    # `selectable`, keeps this case off the selectable/selected_rows guard in the
    # dataset loop -- which runs earlier and would otherwise fire first.
    mode["dataset_ids"] = list(mode["dataset_ids"]) + [str(gated["id"])]


def _mode_rejects_the_classification(contracts):
    mode = next(iter(contracts["full_closure_modes"].values()))
    outside = next(
        value
        for value in ("reader_only", "not_a_classification")
        if value not in set(mode["classifications"])
    )
    by_id = {str(record["id"]): record for record in contracts["datasets"]}
    # Reclassify a dataset the mode already selects, leaving `selectable` alone so
    # the gated-dataset guard one line earlier stays quiet.  Every *currently*
    # selectable record has a classification the modes accept, so there is no
    # unmodified dataset this case could reach instead.
    by_id[str(mode["dataset_ids"][0])]["classification"] = outside


